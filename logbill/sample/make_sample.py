"""Build the sample report shown on the hosted Logbill page, from the test scenario
(tests/scenario.py): three made-up log groups in AWS's documentation account id
123456789012, every AWS call answered by botocore's Stubber. No credentials, no network.

    .venv/bin/python sample/make_sample.py          # rewrite sample/report.html and sample.json
    .venv/bin/python sample/make_sample.py --check  # exit 1 if they are out of date

tests/test_sample.py runs --check, so a change to the report that is not regenerated here
fails the tests. The Worker imports sample.json at build time (worker/src/render/logbill.ts).
"""
import json
import re
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

import boto3  # noqa: E402

from logbill import brand  # noqa: E402
from logbill.locate import locate  # noqa: E402
from logbill.prices import Prices  # noqa: E402
from logbill.report import render_html  # noqa: E402
from tests import scenario  # noqa: E402
from tests.conftest import FIXTURES, StubFactory  # noqa: E402

HTML = HERE / "report.html"
JSON = HERE / "sample.json"
SAMPLE_ACCOUNT = "123456789012"  # the placeholder account id of the AWS documentation
SCHEMA = "logbill.sample/1"

# The scenario's markup row is there to test escaping; a public sample shows a plain line.
_PUBLIC_ROW = scenario._row("GET /health 200 in <Number-1> ms", 1000, 0.1)

BANNER = (
    '<p class="callout accent" role="note"><b>Sample report.</b> Synthetic data from '
    f"{brand.SHORT}'s test scenario: made-up log groups in the AWS documentation account id "
    f"{SAMPLE_ACCOUNT}, not a real account. Run it on yours: {brand.PAGE_URL.split('://', 1)[1]}</p>"
)


def build() -> tuple[str, str]:
    rows = [r for r in scenario.API_ROWS if "<script>" not in r[0]["value"]]
    saved = scenario.API_ROWS
    scenario.API_ROWS = rows + [_PUBLIC_ROW]
    try:
        session = boto3.session.Session(aws_access_key_id="sample", aws_secret_access_key="sample",
                                        region_name="us-east-1")
        factory = StubFactory(session)
        scenario.stub_account(factory)
        report = scenario.scan(factory, Prices.load())
    finally:
        scenario.API_ROWS = saved
    report["sample"] = True
    html = render_html(report)
    html = html.replace("<title>", "<title>Sample: ", 1).replace('<article class="doc">', '<article class="doc">' + BANNER, 1)
    sanitize_check(html, report)
    doc = {"schema": SCHEMA, "note": "Generated by logbill/sample/make_sample.py from tests/scenario.py and "
           "tests/fixtures/repo. Synthetic data. Do not edit by hand.", "report": report,
           "locate": locate_sample(report), "html": html}
    return html, json.dumps(doc, indent=1, sort_keys=True, default=str) + "\n"


def locate_sample(report: dict) -> list[dict]:
    """`logbill locate` on the made-up repo of the tests, for the page's code-locations example."""
    with tempfile.TemporaryDirectory() as d:
        path = Path(d) / "report.json"
        path.write_text(json.dumps(report, default=str))
        found = locate(FIXTURES / "repo", path, top=5)
    return [{"text": p["text"], "monthly_usd": p["monthly_usd"], "group": p["group"],
             "candidates": [{"file": c["file"], "line": c["line"], "text": c["text"]} for c in p["candidates"]]}
            for p in found]


def sanitize_check(html: str, report: dict) -> None:
    """Refuse to write a sample that could carry anything real or active."""
    low = html.lower()
    for bad in ("<script", "<link", "<img", "<iframe", "src=", "href=", "url(", "@import", "http://",
                "https://", "@example.com", scenario.EMAIL):
        if bad in low:
            raise SystemExit(f"sample: refused, found {bad!r}")
    if report.get("account") != SAMPLE_ACCOUNT:
        raise SystemExit("sample: refused, account is not the documentation placeholder")
    accounts = set(re.findall(r"(?<!\d)\d{12}(?!\d)", html))
    if accounts - {SAMPLE_ACCOUNT}:
        raise SystemExit(f"sample: refused, other 12-digit ids: {sorted(accounts - {SAMPLE_ACCOUNT})}")
    if re.search(r"\bon[a-z]+=", low):
        raise SystemExit("sample: refused, an event handler attribute")


def main(argv: list[str]) -> int:
    html, doc = build()
    if "--check" in argv:
        stale = [p.name for p, want in ((HTML, html), (JSON, doc)) if not p.exists() or p.read_text() != want]
        if stale:
            print(f"sample: out of date: {', '.join(stale)}; run sample/make_sample.py", file=sys.stderr)
            return 1
        return 0
    HTML.write_text(html)
    JSON.write_text(doc)
    print(f"sample: wrote {HTML.relative_to(ROOT)} and {JSON.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
